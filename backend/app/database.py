def get_connection_pool() -> ConnectionPool:
    if _pool is None:
        raise RuntimeError("PostgreSQL chưa được khởi tạo.")
    return _pool


def close_database() -> None:
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None
    clear_intent_rule_cache()


@lru_cache(maxsize=32)
def get_active_intent_rules(scenario_id: int | None = None) -> tuple[dict[str, Any], ...]:
    if _pool is None:
        return ()
    with _pool.connection() as connection, connection.cursor() as cursor:
        cursor.execute(
            """
            SELECT id, intent, phrase, phrase_norm, match_type, scenario_id, priority
            FROM intent_phrase_rules
            WHERE enabled = TRUE
              AND (scenario_id IS NULL OR scenario_id = %s)
            ORDER BY priority DESC, id ASC
            """,
            (scenario_id,),
        )
        return tuple(cursor.fetchall())


def clear_intent_rule_cache() -> None:
    get_active_intent_rules.cache_clear()
