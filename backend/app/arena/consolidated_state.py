"""Session-owned summaries/judgements and a shared scenario document store."""

def _table(cursor,name):
    row=cursor.execute("SELECT relkind FROM pg_class WHERE oid=to_regclass(%s)",(name,)).fetchone()
    return bool(row and row['relkind']=='r')


def install(cursor):
    cursor.execute("""ALTER TABLE call_sessions
        ADD COLUMN IF NOT EXISTS memory_text TEXT,
        ADD COLUMN IF NOT EXISTS memory_covered_turn INTEGER,
        ADD COLUMN IF NOT EXISTS memory_max_words SMALLINT,
        ADD COLUMN IF NOT EXISTS memory_word_count SMALLINT,
        ADD COLUMN IF NOT EXISTS memory_provider TEXT,
        ADD COLUMN IF NOT EXISTS memory_updated_at TIMESTAMPTZ,
        ADD COLUMN IF NOT EXISTS practice_judgement TEXT CHECK(practice_judgement IN ('benign','fraud','uncertain')),
        ADD COLUMN IF NOT EXISTS judged_at TIMESTAMPTZ,
        ADD COLUMN IF NOT EXISTS judgement_reason TEXT NOT NULL DEFAULT '',
        ADD COLUMN IF NOT EXISTS judgement_evaluation JSONB;
        CREATE TABLE IF NOT EXISTS scenario_documents (
            document_kind TEXT NOT NULL CHECK(document_kind IN ('draft','review')),
            document_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
            document JSONB NOT NULL,creator_id TEXT REFERENCES app_users(user_id) ON DELETE SET NULL,
            revision INTEGER NOT NULL DEFAULT 1 CHECK(revision>0),
            status TEXT NOT NULL CHECK(status IN ('draft','pending','approved','rejected')),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            reviewed_by TEXT REFERENCES app_users(user_id) ON DELETE SET NULL,reviewed_at TIMESTAMPTZ,
            published_version_id BIGINT REFERENCES scenario_versions(version_id),
            PRIMARY KEY(document_kind,document_id),
            CHECK((document_kind='draft' AND status='draft') OR (document_kind='review' AND status<>'draft')));
        CREATE INDEX IF NOT EXISTS scenario_documents_owner ON scenario_documents(creator_id,document_kind,updated_at DESC);""")
    if _table(cursor,'conversation_memories'):
        cursor.execute("""UPDATE call_sessions s SET memory_text=m.summary_text,memory_covered_turn=m.covered_turn,
            memory_max_words=m.max_words,memory_word_count=m.word_count,memory_provider=m.provider,memory_updated_at=m.updated_at
            FROM conversation_memories m WHERE m.session_id=s.session_id;
            DROP TABLE conversation_memories;""")
    if _table(cursor,'practice_judgements'):
        cursor.execute("""UPDATE call_sessions s SET practice_judgement=j.judgement,judged_at=j.created_at,
            judgement_reason=j.reason,judgement_evaluation=j.evaluation FROM practice_judgements j WHERE j.session_id=s.session_id;
            DROP TABLE practice_judgements;""")
    migrated=False
    if _table(cursor,'practice_admin_drafts'):
        cursor.execute("""INSERT INTO scenario_documents(document_kind,document_id,document,creator_id,revision,status,created_at,updated_at)
            SELECT 'draft',draft_id,document,owner_id,revision,'draft',updated_at,updated_at FROM practice_admin_drafts;
            DROP TABLE practice_admin_drafts;""");migrated=True
    if _table(cursor,'practice_reviews'):
        cursor.execute("""INSERT INTO scenario_documents(document_kind,document_id,document,creator_id,status,created_at,updated_at,reviewed_by,reviewed_at,published_version_id)
            SELECT 'review',review_id,document,submitted_by,status,created_at,COALESCE(reviewed_at,created_at),reviewed_by,reviewed_at,published_version_id FROM practice_reviews;
            DROP TABLE practice_reviews;""");migrated=True
    if migrated:
        cursor.execute("""SELECT setval(pg_get_serial_sequence('scenario_documents','document_id'),
            GREATEST(1,COALESCE((SELECT max(document_id)+1 FROM scenario_documents),1)),false)""")
    cursor.execute("""CREATE OR REPLACE VIEW conversation_memories AS SELECT session_id,
        memory_text AS summary_text,memory_covered_turn AS covered_turn,memory_max_words AS max_words,
        memory_word_count AS word_count,memory_provider AS provider,memory_updated_at AS updated_at
        FROM call_sessions WHERE memory_text IS NOT NULL;
        CREATE OR REPLACE VIEW practice_judgements AS SELECT session_id,practice_judgement AS judgement,
        judged_at AS created_at,judgement_reason AS reason,judgement_evaluation AS evaluation
        FROM call_sessions WHERE practice_judgement IS NOT NULL;
        CREATE OR REPLACE VIEW practice_admin_drafts AS SELECT document_id AS draft_id,creator_id AS owner_id,
        document,revision,updated_at FROM scenario_documents WHERE document_kind='draft';
        CREATE OR REPLACE VIEW practice_reviews AS SELECT document_id AS review_id,document,status,
        creator_id AS submitted_by,reviewed_by,created_at,reviewed_at,published_version_id
        FROM scenario_documents WHERE document_kind='review';
        DO $$ BEGIN
          IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='call_sessions'::regclass AND conname='session_memory_valid') THEN
            ALTER TABLE call_sessions ADD CONSTRAINT session_memory_valid CHECK(
                memory_text IS NULL OR (char_length(memory_text)<=40000 AND memory_covered_turn>=0
                AND memory_max_words BETWEEN 20 AND 500 AND memory_word_count BETWEEN 1 AND memory_max_words
                AND memory_covered_turn IS NOT NULL AND memory_max_words IS NOT NULL AND memory_word_count IS NOT NULL
                AND memory_provider IS NOT NULL AND memory_updated_at IS NOT NULL));
          END IF;
        END $$;""")
