def install(cursor):
    cursor.execute('''CREATE TABLE IF NOT EXISTS data_review_runs (
        run_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
        status TEXT NOT NULL CHECK(status IN ('running','completed','failed')),
        trigger TEXT NOT NULL, actor_id TEXT REFERENCES app_users(user_id) ON DELETE SET NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        finished_at TIMESTAMPTZ,stats JSONB NOT NULL DEFAULT '{}');
        CREATE UNIQUE INDEX IF NOT EXISTS data_review_single_running ON data_review_runs(status) WHERE status='running';
        CREATE TABLE IF NOT EXISTS data_review_items (
        item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        kind TEXT NOT NULL CHECK(kind IN ('intent','rule','stale_session','duplicate','dialogue')),
        source_key TEXT NOT NULL,source_hash TEXT NOT NULL,original JSONB NOT NULL,
        suggestion JSONB NOT NULL DEFAULT '{}',analysis_status TEXT NOT NULL DEFAULT 'pending'
          CHECK(analysis_status IN ('pending','ready','failed','not_configured')),
        decision TEXT NOT NULL DEFAULT 'pending' CHECK(decision IN ('pending','accepted','rejected')),
        run_id UUID REFERENCES data_review_runs(run_id) ON DELETE SET NULL,
        reviewed_by TEXT REFERENCES app_users(user_id) ON DELETE SET NULL,reviewed_at TIMESTAMPTZ,
        result JSONB,created_at TIMESTAMPTZ NOT NULL DEFAULT now(),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        UNIQUE(kind,source_key,source_hash));
        CREATE INDEX IF NOT EXISTS data_review_queue ON data_review_items(decision,analysis_status,item_id);
        CREATE TABLE IF NOT EXISTS reviewed_utterances (
        turn_id BIGINT PRIMARY KEY REFERENCES call_turns(turn_id) ON DELETE CASCADE,
        corrected_text TEXT NOT NULL,intent TEXT NOT NULL,review_item_id BIGINT NOT NULL REFERENCES data_review_items(item_id),
        reviewed_by TEXT REFERENCES app_users(user_id) ON DELETE SET NULL,reviewed_at TIMESTAMPTZ NOT NULL DEFAULT now());
        ALTER TABLE call_sessions ADD COLUMN IF NOT EXISTS abandoned_at TIMESTAMPTZ;''')


def fingerprint(value):
    return hashlib.sha256(json.dumps(value,sort_keys=True,ensure_ascii=False,default=str).encode()).hexdigest()


def clean(value):
    if isinstance(value,str):return mask(value)
    if isinstance(value,dict):return {k:(v if k=='session_id' else clean(v)) for k,v in value.items()}
    if isinstance(value,list):return [clean(v) for v in value]
    return value


def create_run(actor_id=None,trigger='manual'):
    with get_connection_pool().connection() as c:
        c.execute('SELECT pg_advisory_xact_lock(736219043)')
        c.execute("UPDATE data_review_runs SET status='failed',finished_at=now(),stats=stats || '{\"error\":\"interrupted\"}' WHERE status='running' AND updated_at<now()-interval '10 minutes'")
        row=c.execute("SELECT run_id FROM data_review_runs WHERE status='running'").fetchone()
        if row:return row['run_id'],False
        row=c.execute("INSERT INTO data_review_runs(status,trigger,actor_id) VALUES('running',%s,%s) RETURNING run_id",(trigger,actor_id)).fetchone()
        return row['run_id'],True


def candidate_snapshot(c,candidate_id):
    row=c.execute('''SELECT r.candidate_id,r.turn_id,r.session_id::text,r.scenario_id,r.requested_action,
          r.caller_text,r.user_text_masked AS player_text,r.detected_intent,r.review_status,
          t.turn_no,v.definition->>'title' AS scenario_title
        FROM intent_review_candidates r JOIN call_turns t USING(turn_id)
        JOIN call_sessions s ON s.session_id=r.session_id JOIN scenario_versions v ON v.version_id=s.scenario_version_id
        WHERE r.candidate_id=%s''',(candidate_id,)).fetchone()
    if not row:return None
    row['recent_turns']=c.execute('''SELECT user_text_masked AS player_text,bot_reply_text AS caller_text
        FROM call_turns WHERE session_id=%s AND turn_no<%s ORDER BY turn_no DESC LIMIT 3''',(row['session_id'],row['turn_no'])).fetchall()[::-1]
    return clean(row)


def rule_snapshot(c,rule_id):
    row=c.execute('''SELECT r.id,r.intent,r.phrase,r.phrase_norm,r.match_type,r.priority,r.enabled,r.scenario_id,
        s.title AS scenario_title FROM intent_phrase_rules r LEFT JOIN scenarios s USING(scenario_id) WHERE r.id=%s''',(rule_id,)).fetchone()
    if not row:return None
    row['examples']=c.execute('''SELECT caller_text,user_text_masked AS player_text,requested_action,detected_intent
        FROM intent_review_candidates WHERE scenario_id IS NOT DISTINCT FROM %s AND position(%s in user_text_masked)>0
        ORDER BY candidate_id DESC LIMIT 3''',(row['scenario_id'],row['phrase'])).fetchall()
    return clean(row)


def dataset_duplicates(workspace):
    path=workspace/'review.json'
    if not path.exists() or path.stat().st_size>2_000_000:return []
    try:review=json.loads(path.read_text(encoding='utf-8'))
    except (OSError,ValueError):return []
    groups=defaultdict(list)
    for row in review.get('rows',[])[:10000]:
        if isinstance(row,dict) and isinstance(row.get('text'),str) and row.get('sample'):
            key=normalize_phrase(row['text'])
            if key:groups[key].append(row)
    return [{'dataset_only':True,'sample_ids':sorted(row['sample'] for row in group),
        'player_text':mask(group[0]['text']),
        'labels':sorted({str(row.get('intent') or 'chưa duyệt') for row in group})}
        for group in groups.values() if len(group)>1]


def put(c,kind,key,original,run_id,suggestion=None):
    digest=fingerprint(original)
    if kind=='intent':
        row=c.execute("SELECT item_id,source_hash,decision FROM data_review_items WHERE kind='intent' AND source_key=%s AND candidate_data IS NOT NULL FOR UPDATE",(str(key),)).fetchone()
        if row:
            if row['decision']=='pending':
                c.execute("""UPDATE data_review_items SET original=%s,source_hash=%s,run_id=%s,
                    suggestion=CASE WHEN source_hash=%s THEN suggestion ELSE '{}'::jsonb END,
                    analysis_status=CASE WHEN source_hash=%s THEN analysis_status ELSE 'pending' END,updated_at=now()
                    WHERE item_id=%s""",(Jsonb(original),digest,run_id,digest,digest,row['item_id']))
            return
    c.execute('''UPDATE data_review_items SET decision='rejected',reviewed_at=now(),updated_at=now(),
        result='{"action":"superseded","note":"Nguồn đã thay đổi; đã tạo đề xuất mới."}'::jsonb
        WHERE kind=%s AND source_key=%s AND source_hash<>%s AND decision='pending' ''',(kind,str(key),digest))
    c.execute('''INSERT INTO data_review_items(kind,source_key,source_hash,original,run_id,suggestion,analysis_status)
        VALUES(%s,%s,%s,%s,%s,%s,%s) ON CONFLICT(kind,source_key,source_hash) DO NOTHING''',
        (kind,str(key),digest,Jsonb(original),run_id,Jsonb(suggestion or {}),'ready' if suggestion else 'pending'))


def scan(run_id,session_id=None):
    with get_connection_pool().connection() as c:
        candidates=c.execute('''SELECT r.candidate_id FROM intent_review_candidates r
          WHERE r.review_status='pending' AND (%s::uuid IS NULL OR r.session_id=%s::uuid)
          ORDER BY EXISTS(SELECT 1 FROM data_review_items d WHERE d.kind='intent' AND d.source_key=r.candidate_id::text),r.candidate_id LIMIT 200''',
          (session_id,session_id)).fetchall()
        for row in candidates:
            snapshot=candidate_snapshot(c,row['candidate_id'])
            put(c,'intent',row['candidate_id'],snapshot,run_id)
        if session_id:return
        for row in c.execute("SELECT id FROM intent_phrase_rules r WHERE enabled ORDER BY EXISTS(SELECT 1 FROM data_review_items d WHERE d.kind='rule' AND d.source_key=r.id::text),id LIMIT 100").fetchall():
            put(c,'rule',row['id'],rule_snapshot(c,row['id']),run_id)
        stale=c.execute('''SELECT s.session_id::text,s.turn_no,s.interaction_mode,
            GREATEST(s.started_at,COALESCE(max(t.created_at),s.started_at))::text AS last_activity
            FROM call_sessions s LEFT JOIN call_turns t USING(session_id)
            WHERE s.ended_at IS NULL AND s.abandoned_at IS NULL GROUP BY s.session_id
            HAVING GREATEST(s.started_at,COALESCE(max(t.created_at),s.started_at))<now()-interval '24 hours'
            ORDER BY s.started_at LIMIT 200''').fetchall()
        for row in stale:put(c,'stale_session',row['session_id'],dict(row),run_id,{'rationale':'Không có lượt thoại mới trong hơn 24 giờ. Đánh dấu bỏ dở, không chấm là hoàn thành.'})
        # Exact text AND caller/action/scenario must match; no cross-context merges.
        groups=c.execute('''SELECT min(candidate_id) AS keep_id,array_agg(candidate_id ORDER BY candidate_id) AS candidate_ids,
          scenario_id,caller_text,user_text_masked AS player_text,requested_action
          FROM intent_review_candidates WHERE review_status='pending'
          GROUP BY scenario_id,caller_text,user_text_masked,requested_action HAVING count(*)>1 LIMIT 100''').fetchall()
        for row in groups:put(c,'duplicate',row['keep_id'],dict(row),run_id,{'rationale':'Các mục cùng câu người chơi và cùng ngữ cảnh. Giữ mục đầu, bỏ các bản trùng khỏi hàng chờ; không xóa lịch sử.'})
        from app.api.rasa_review_routes import _workspace
        for group in dataset_duplicates(_workspace()):
            put(c,'duplicate','rasa:'+fingerprint(group['sample_ids']),group,run_id,{
                'rationale':'Các mẫu Rasa trùng chữ sau chuẩn hóa nhưng không có đủ ngữ cảnh để tự gộp. Bộ xuất Rasa đã loại câu trùng/nhãn mâu thuẫn. Chỉ ghi nhận cảnh báo, không sửa file mẫu.'})
        from app.arena.service_completion import service_line_matches_step
        history=c.execute('''SELECT t.turn_id,t.bot_reply_text,n.requested_action,v.definition->'payload' AS payload
          FROM call_turns t JOIN call_sessions s USING(session_id) JOIN scenario_versions v ON v.version_id=s.scenario_version_id
          JOIN dialogue_nodes n ON n.node_id=t.target_node_id WHERE NOT n.is_terminal AND t.line_source<>'fixed'
          ORDER BY t.turn_id DESC LIMIT 500''').fetchall()
        for row in history:
            context={'scenario_kind':row['payload'].get('scenario_kind'),'scenario_family':row['payload'].get('family'),'requested_action':row['requested_action']}
            if not service_line_matches_step(row['bot_reply_text'],context):
                original=clean({'turn_id':row['turn_id'],'bot_reply_text':row['bot_reply_text'],'requested_action':row['requested_action']})
                put(c,'dialogue',row['turn_id'],original,run_id,{'rationale':'Lời thoại cũ không thể hiện đúng yêu cầu của bước. Ghi nhận để rà soát; lịch sử được giữ nguyên.'})


def run_review(run_id,limit=5,session_id=None,*,kind='all'):
    limit=max(1,min(20,int(limit)))
    stats={'analyzed':0,'failed':0,'not_configured':0}
    try:
        scan(run_id,session_id)
        with get_connection_pool().connection() as c:
            items=c.execute('''SELECT * FROM data_review_items WHERE decision='pending' AND kind IN ('intent','rule')
              AND analysis_status IN ('pending','failed','not_configured') AND (%s::uuid IS NULL OR original->>'session_id'=%s)
              AND (%s='all' OR kind=%s)
              ORDER BY CASE WHEN analysis_status='pending' THEN 0 ELSE 1 END,item_id LIMIT %s''',
              (session_id,str(session_id) if session_id else None,kind,kind,limit)).fetchall()
        for item in items:
            try:
                context={key:value for key,value in item['original'].items() if key in {
                    'requested_action','caller_text','player_text','detected_intent','scenario_title',
                    'recent_turns','intent','phrase','examples','match_type'}}
                suggestion=request_review({**context,'review_kind':item['kind']})
                status='ready';stats['analyzed']+=1
            except Exception as exc:
                status='not_configured' if str(exc)=='not_configured' else 'failed'
                suggestion={'rationale':'Chưa cấu hình LLM nhắn tin.' if status=='not_configured' else 'LLM chưa trả kết quả hợp lệ. Có thể chạy lại đợt sau.'}
                stats[status]+=1
            with get_connection_pool().connection() as c:
                c.execute('''UPDATE data_review_items SET suggestion=%s,analysis_status=%s,run_id=%s,updated_at=now()
                  WHERE item_id=%s AND decision='pending' ''',(Jsonb(suggestion),status,run_id,item['item_id']))
                if item['kind']=='intent':
                    c.execute('''UPDATE intent_review_candidates SET suggested_intent=%s,suggested_phrase=%s,confidence=%s,
                        rationale=%s,analysis_status=%s WHERE candidate_id=%s AND review_status='pending' ''',
                        (suggestion.get('intent'),None,suggestion.get('confidence'),suggestion['rationale'],
                         'analyzed' if status=='ready' else status,int(item['source_key'])))
                c.execute("UPDATE data_review_runs SET stats=%s,updated_at=now() WHERE run_id=%s AND status='running'",(Jsonb(stats),run_id))
        with get_connection_pool().connection() as c:
            c.execute("UPDATE data_review_runs SET status='completed',stats=%s,updated_at=now(),finished_at=now() WHERE run_id=%s AND status='running'",(Jsonb(stats),run_id))
    except Exception:
        with get_connection_pool().connection() as c:
            c.execute("UPDATE data_review_runs SET status='failed',stats=%s,updated_at=now(),finished_at=now() WHERE run_id=%s",(Jsonb({**stats,'error':'scan_failed'}),run_id))


def analyze_session(session_id):
    import os
    if os.getenv('DATA_REVIEW_AUTO','true').lower() not in {'true','1'} or not configured():return
    run_id,created=create_run(trigger='session_finished')
    if created:run_review(run_id,limit=2,session_id=session_id)


def decide(item_id,body,actor_id):
    with get_connection_pool().connection() as c:
        c.execute('SELECT pg_advisory_xact_lock(736219044)')
        actor=c.execute('SELECT role,is_locked FROM app_users WHERE user_id=%s FOR SHARE',(actor_id,)).fetchone()
        if not actor or actor['role']!='admin' or actor['is_locked']:raise PermissionError('Quyền quản trị không còn hiệu lực.')
        item=c.execute('SELECT * FROM data_review_items WHERE item_id=%s FOR UPDATE',(item_id,)).fetchone()
        if not item:raise KeyError(item_id)
        if item['decision']!='pending':raise ValueError('Mục này đã được xử lý. Hãy tải lại.')
        if body.expected_hash!=item['source_hash']:raise ValueError('Dữ liệu đã thay đổi. Hãy tải lại.')
        result={'note':body.note}
        if body.decision=='accepted':
            if item['analysis_status']!='ready':raise ValueError('Chưa có đề xuất hợp lệ để duyệt.')
            original=item['original'];kind=item['kind']
            if kind in {'intent','rule'}:
                if kind=='intent':c.execute('SELECT candidate_id FROM intent_review_candidates WHERE candidate_id=%s FOR UPDATE',(int(item['source_key']),))
                else:c.execute('SELECT id FROM intent_phrase_rules WHERE id=%s FOR UPDATE',(int(item['source_key']),))
                current=candidate_snapshot(c,int(item['source_key'])) if kind=='intent' else rule_snapshot(c,int(item['source_key']))
                if fingerprint(current)!=item['source_hash']:raise ValueError('Nguồn đã được sửa hoặc duyệt ở nơi khác. Chạy quét lại.')
                label=body.intent or item['suggestion'].get('intent')
                if label not in INTENTS:raise ValueError('Chọn một nhãn hợp lệ.')
                if kind=='intent':
                    text=(body.corrected_text if body.corrected_text is not None else item['suggestion'].get('corrected_text')) or original['player_text']
                    if label!='unknown' and item['suggestion'].get('needs_audio') and not body.note.strip():
                        raise ValueError('Mẫu còn nghi nghe nhầm. Nhập lý do xác nhận hoặc chọn unknown để bỏ qua.')
                    if not 1<=len(text.strip())<=2000 or mask(text)!=text:raise ValueError('Bản hiệu chỉnh trống, quá dài hoặc chứa email/chuỗi số nhạy cảm.')
                    if label!='unknown':
                        c.execute('''INSERT INTO reviewed_utterances(turn_id,corrected_text,intent,review_item_id,reviewed_by)
                          VALUES(%s,%s,%s,%s,%s) ON CONFLICT(turn_id) DO UPDATE SET corrected_text=EXCLUDED.corrected_text,
                          intent=EXCLUDED.intent,review_item_id=EXCLUDED.review_item_id,reviewed_by=EXCLUDED.reviewed_by,reviewed_at=now()''',
                          (original['turn_id'],text.strip(),label,item_id,actor_id))
                    c.execute("UPDATE intent_review_candidates SET review_status=%s,reviewed_at=now() WHERE candidate_id=%s",('rejected' if label=='unknown' else 'approved',int(item['source_key'])))
                    result.update(intent=label,corrected_text=text.strip(),action='skip' if label=='unknown' else 'reviewed_sample')
                else:
                    if label=='unknown':raise ValueError('Không dùng unknown làm luật. Hãy bỏ qua đề xuất.')
                    c.execute('UPDATE intent_phrase_rules SET intent=%s WHERE id=%s',(label,int(item['source_key'])))
                    result.update(intent=label,action='rule_label_updated')
            elif kind=='stale_session':
                row=c.execute('''UPDATE call_sessions s SET abandoned_at=now() WHERE session_id=%s AND ended_at IS NULL AND abandoned_at IS NULL
                  AND GREATEST(started_at,COALESCE((SELECT max(created_at) FROM call_turns t WHERE t.session_id=s.session_id),started_at))<now()-interval '24 hours'
                  AND turn_no=%s RETURNING session_id''',(item['source_key'],original['turn_no'])).fetchone()
                if not row:raise ValueError('Phiên đã hoạt động lại hoặc đã kết thúc. Không đánh dấu bỏ dở.')
                result['action']='marked_abandoned'
            elif kind=='duplicate':
                if original.get('dataset_only'):
                    result['action']='dataset_duplicate_acknowledged'
                else:
                    ids=original['candidate_ids']
                    c.execute('SELECT candidate_id FROM intent_review_candidates WHERE candidate_id=ANY(%s) ORDER BY candidate_id FOR UPDATE',(ids,))
                    snapshots=[candidate_snapshot(c,n) for n in ids]
                    if any(not row or row['review_status']!='pending' for row in snapshots):raise ValueError('Nhóm trùng đã được xử lý. Chạy quét lại.')
                    keys={(row['scenario_id'],row['caller_text'],row['player_text'],row['requested_action']) for row in snapshots}
                    if len(keys)!=1:raise ValueError('Các câu không còn cùng ngữ cảnh.')
                    c.execute("UPDATE intent_review_candidates SET review_status='rejected',reviewed_at=now() WHERE candidate_id=ANY(%s)",(ids[1:],))
                    result.update(action='duplicate_queue_skipped',count=len(ids)-1)
            else:result['action']='historical_issue_acknowledged'
        c.execute('''UPDATE data_review_items SET decision=%s,reviewed_by=%s,reviewed_at=now(),result=%s,updated_at=now()
          WHERE item_id=%s''',(body.decision,actor_id,Jsonb(result),item_id))
    clear_intent_rule_cache()
    return result
