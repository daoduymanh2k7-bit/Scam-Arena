"""Immutable published graph versions, with sessions pinned to their original graph."""
import hashlib
import json
import secrets

from psycopg.types.json import Jsonb


def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def install(cursor):
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS scenario_versions (
            version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            scenario_id BIGINT NOT NULL REFERENCES scenarios(scenario_id),
            revision INTEGER NOT NULL CHECK(revision>0),
            status TEXT NOT NULL CHECK(status IN ('draft','published')),
            definition JSONB NOT NULL,
            content_hash TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            UNIQUE(scenario_id,revision), UNIQUE(scenario_id,content_hash)
        );
        CREATE TABLE IF NOT EXISTS practice_events (
            session_id UUID NOT NULL REFERENCES call_sessions(session_id) ON DELETE CASCADE,
            event_type TEXT NOT NULL CHECK(event_type='check_order'),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(session_id,event_type)
        );
        ALTER TABLE practice_events DROP CONSTRAINT IF EXISTS practice_events_event_type_check;
        ALTER TABLE practice_events ADD CONSTRAINT practice_events_event_type_check CHECK(event_type IN
            ('check_order','check_context','read_message','verify_official','open_requested_link','share_demo_code'));
        CREATE TABLE IF NOT EXISTS practice_bundle_versions (
            scenario_name TEXT NOT NULL,bundle_revision TEXT NOT NULL,
            version_id BIGINT NOT NULL REFERENCES scenario_versions(version_id),
            PRIMARY KEY(scenario_name,bundle_revision)
        );
        ALTER TABLE scenarios ADD COLUMN IF NOT EXISTS scenario_kind TEXT NOT NULL DEFAULT 'fraud'
            CHECK(scenario_kind IN ('fraud','benign'));
        ALTER TABLE scenarios ADD COLUMN IF NOT EXISTS family TEXT NOT NULL DEFAULT 'legacy';
        ALTER TABLE scenarios ADD COLUMN IF NOT EXISTS selection_weight REAL NOT NULL DEFAULT 1
            CHECK(selection_weight>0 AND selection_weight<10001);
        ALTER TABLE scenarios ADD COLUMN IF NOT EXISTS active_version_id BIGINT REFERENCES scenario_versions(version_id);
        ALTER TABLE dialogue_nodes ADD COLUMN IF NOT EXISTS scenario_version_id BIGINT REFERENCES scenario_versions(version_id);
        ALTER TABLE call_sessions ADD COLUMN IF NOT EXISTS scenario_version_id BIGINT REFERENCES scenario_versions(version_id);
        ALTER TABLE call_sessions ADD COLUMN IF NOT EXISTS random_seed TEXT;
        ALTER TABLE call_sessions ADD COLUMN IF NOT EXISTS case_parameters JSONB NOT NULL DEFAULT '{}'::jsonb;
        ALTER TABLE call_sessions ADD COLUMN IF NOT EXISTS world_state JSONB NOT NULL DEFAULT '{}'::jsonb;
        ALTER TABLE call_sessions ADD COLUMN IF NOT EXISTS exercise_mode TEXT NOT NULL DEFAULT 'training'
            CHECK(exercise_mode IN ('training','assessment'));
    """)
    from app.arena.consolidated_state import install as consolidate_state
    consolidate_state(cursor)
    cursor.execute("SELECT * FROM scenarios WHERE active_version_id IS NULL ORDER BY scenario_id FOR UPDATE")
    for scenario in cursor.fetchall():
        sid = scenario['scenario_id']
        cursor.execute("""SELECT node_id,node_key,stage,objective,tactic,requested_action,max_turns,
                                  is_start,is_terminal,outcome,timeout_next_node_id
                           FROM dialogue_nodes WHERE scenario_id=%s ORDER BY node_id""", (sid,))
        nodes = cursor.fetchall()
        cursor.execute("""SELECT l.node_id,l.line_text,l.is_reprompt,l.enabled FROM dialogue_lines l
                           JOIN dialogue_nodes n USING(node_id) WHERE n.scenario_id=%s AND l.source='fixed'
                           ORDER BY l.line_id""", (sid,))
        fixed = cursor.fetchall()
        cursor.execute("""SELECT t.from_node_id,t.to_node_id,t.intent,t.score_delta,t.feedback,t.critical
                           FROM dialogue_transitions t JOIN dialogue_nodes n ON n.node_id=t.from_node_id
                           WHERE n.scenario_id=%s ORDER BY t.transition_id""", (sid,))
        transitions = cursor.fetchall()
        cursor.execute("SELECT intent,end_outcome,score_delta,feedback,critical FROM intent_defaults ORDER BY intent")
        definition = {'title': scenario['title'], 'payload': scenario['payload'],
                      'base_score': scenario['base_score'], 'max_turns': scenario['max_turns'],
                      'scenario_kind': 'fraud', 'family': scenario['payload'].get('category', 'legacy'),
                      'nodes': nodes, 'fixed_lines': fixed, 'transitions': transitions,
                      'intent_defaults': cursor.fetchall(), 'origin': 'legacy-baseline'}
        cursor.execute("""INSERT INTO scenario_versions(scenario_id,revision,status,definition,content_hash)
                           VALUES(%s,1,'draft',%s,%s) RETURNING version_id""", (sid, Jsonb(definition), digest(definition)))
        vid = cursor.fetchone()['version_id']
        cursor.execute("UPDATE dialogue_nodes SET scenario_version_id=%s WHERE scenario_id=%s", (vid, sid))
        cursor.execute("UPDATE call_sessions SET scenario_version_id=%s WHERE scenario_id=%s AND scenario_version_id IS NULL", (vid, sid))
        cursor.execute("UPDATE scenarios SET active_version_id=%s,family=%s WHERE scenario_id=%s",
                       (vid, definition['family'], sid))
        cursor.execute("UPDATE scenario_versions SET status='published' WHERE version_id=%s", (vid,))
    cursor.execute("""
        ALTER TABLE dialogue_nodes DROP CONSTRAINT IF EXISTS dialogue_nodes_scenario_id_node_key_key;
        DROP INDEX IF EXISTS dialogue_nodes_one_start_idx;
        CREATE UNIQUE INDEX dialogue_nodes_one_start_idx ON dialogue_nodes(scenario_version_id) WHERE is_start;
        CREATE UNIQUE INDEX IF NOT EXISTS dialogue_nodes_version_key_idx ON dialogue_nodes(scenario_version_id,node_key);
        CREATE INDEX IF NOT EXISTS call_sessions_version_idx ON call_sessions(scenario_version_id);
        CREATE UNIQUE INDEX IF NOT EXISTS scenario_versions_identity_idx ON scenario_versions(version_id,scenario_id);
        CREATE UNIQUE INDEX IF NOT EXISTS dialogue_nodes_identity_version_idx ON dialogue_nodes(node_id,scenario_version_id);
        DO $$ BEGIN
            IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conname='nodes_version_owner_fk') THEN
                ALTER TABLE dialogue_nodes ADD CONSTRAINT nodes_version_owner_fk
                    FOREIGN KEY(scenario_version_id,scenario_id) REFERENCES scenario_versions(version_id,scenario_id);
                ALTER TABLE call_sessions ADD CONSTRAINT sessions_version_owner_fk
                    FOREIGN KEY(scenario_version_id,scenario_id) REFERENCES scenario_versions(version_id,scenario_id);
                ALTER TABLE call_sessions ADD CONSTRAINT sessions_node_version_fk
                    FOREIGN KEY(current_node_id,scenario_version_id) REFERENCES dialogue_nodes(node_id,scenario_version_id);
            END IF;
        END $$;
        UPDATE call_sessions SET random_seed=gen_random_uuid()::text WHERE random_seed IS NULL;
        ALTER TABLE dialogue_nodes ALTER COLUMN scenario_version_id SET NOT NULL;
        ALTER TABLE call_sessions ALTER COLUMN scenario_version_id SET NOT NULL;
        ALTER TABLE call_sessions ALTER COLUMN random_seed SET NOT NULL;
        ALTER TABLE call_sessions ALTER COLUMN random_seed SET DEFAULT gen_random_uuid()::text;
    """)
    _install_guards(cursor)
    from pathlib import Path
    root = Path(__file__).resolve().parents[3]
    for name in ('delivery-ordinary','delivery-impostor'):
        cursor.execute('SELECT scenario_id FROM scenarios WHERE scenario_name=%s',(name,))
        if not cursor.fetchone():
            publish_document(cursor,json.loads((root/'data/scenarios'/f'{name}.json').read_text(encoding='utf-8')))
    from app.arena.practice_catalog import documents
    base=json.loads((root/'data/scenarios/bank.json').read_text(encoding='utf-8'))
    for document in documents(base):
        bundle='practice-bundle-v4-support-context' if document['family']=='support' else 'practice-bundle-v2'
        cursor.execute('SELECT version_id FROM practice_bundle_versions WHERE scenario_name=%s AND bundle_revision=%s',(document['id'],bundle))
        if cursor.fetchone(): continue
        cursor.execute("""SELECT s.active_version_id,EXISTS(SELECT 1 FROM practice_reviews r
                           WHERE r.published_version_id=s.active_version_id AND r.status='approved') AS edited
                           FROM scenarios s WHERE s.scenario_name=%s""",(document['id'],))
        existing=cursor.fetchone()
        version=existing['active_version_id'] if existing and existing['edited'] else publish_document(cursor,document)
        cursor.execute('INSERT INTO practice_bundle_versions(scenario_name,bundle_revision,version_id) VALUES(%s,%s,%s)',(document['id'],bundle,version))


def _install_guards(cursor):
    cursor.execute("""
        CREATE OR REPLACE FUNCTION guard_published_scenario_version() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            IF OLD.status='published' THEN RAISE EXCEPTION 'Published scenario versions are immutable'; END IF;
            IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
        END $$;
        DROP TRIGGER IF EXISTS immutable_scenario_version ON scenario_versions;
        CREATE TRIGGER immutable_scenario_version BEFORE UPDATE OR DELETE ON scenario_versions
            FOR EACH ROW EXECUTE FUNCTION guard_published_scenario_version();
        CREATE OR REPLACE FUNCTION guard_published_graph() RETURNS trigger LANGUAGE plpgsql AS $$
        DECLARE vid bigint; frozen boolean;
        BEGIN
            IF TG_TABLE_NAME='dialogue_nodes' THEN
                vid=COALESCE(OLD.scenario_version_id,NEW.scenario_version_id);
                IF TG_OP<>'DELETE' AND NEW.timeout_next_node_id IS NOT NULL AND NOT EXISTS (
                    SELECT 1 FROM dialogue_nodes WHERE node_id=NEW.timeout_next_node_id AND scenario_version_id=NEW.scenario_version_id
                ) THEN RAISE EXCEPTION 'Cross-version timeout target'; END IF;
            ELSIF TG_TABLE_NAME='dialogue_transitions' THEN
                SELECT scenario_version_id INTO vid FROM dialogue_nodes WHERE node_id=COALESCE(OLD.from_node_id,NEW.from_node_id);
                IF TG_OP<>'DELETE' AND NOT EXISTS (
                    SELECT 1 FROM dialogue_nodes WHERE node_id=NEW.to_node_id AND scenario_version_id=vid
                ) THEN RAISE EXCEPTION 'Cross-version transition target'; END IF;
            ELSE
                IF TG_OP='INSERT' AND NEW.source='llm' THEN RETURN NEW; END IF;
                IF TG_OP<>'INSERT' AND OLD.source='llm' AND (TG_OP='DELETE' OR NEW.source='llm') THEN
                    IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
                END IF;
                IF TG_OP='UPDATE' AND (to_jsonb(NEW)-'use_count')=(to_jsonb(OLD)-'use_count') THEN RETURN NEW; END IF;
                SELECT scenario_version_id INTO vid FROM dialogue_nodes WHERE node_id=COALESCE(OLD.node_id,NEW.node_id);
            END IF;
            SELECT status='published' INTO frozen FROM scenario_versions WHERE version_id=vid;
            IF frozen THEN RAISE EXCEPTION 'Published scenario graphs are immutable'; END IF;
            IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
        END $$;
        DROP TRIGGER IF EXISTS immutable_scenario_node ON dialogue_nodes;
        CREATE TRIGGER immutable_scenario_node BEFORE INSERT OR UPDATE OR DELETE ON dialogue_nodes FOR EACH ROW EXECUTE FUNCTION guard_published_graph();
        DROP TRIGGER IF EXISTS immutable_scenario_edge ON dialogue_transitions;
        CREATE TRIGGER immutable_scenario_edge BEFORE INSERT OR UPDATE OR DELETE ON dialogue_transitions FOR EACH ROW EXECUTE FUNCTION guard_published_graph();
        DROP TRIGGER IF EXISTS immutable_scenario_fixed_line ON dialogue_lines;
        CREATE TRIGGER immutable_scenario_fixed_line BEFORE INSERT OR UPDATE OR DELETE ON dialogue_lines FOR EACH ROW EXECUTE FUNCTION guard_published_graph();
    """)


def session_seed():
    return secrets.token_hex(16)


def validated_document(raw):
    from app.arena.scenario_loader import _load_one
    document = _load_one(raw, 'publication').model_dump(mode='json')
    for stage in document['stages']:
        if len(stage['opening_line'])>400 or len(' '.join(stage['fallback_lines']))>400:
            raise ValueError('Lời thoại hoặc tổng câu hỏi lại vượt giới hạn 400 ký tự.')
    return document


def publish_document(cursor, raw, openings=()):
    """Explicit authoring operation, never an automatic startup rewrite."""
    document=validated_document(raw)
    if document['status'] != 'published':
        raise ValueError('Only reviewed published documents may be activated')
    openings = list(openings)
    if any(not isinstance(line, str) or not 5 <= len(line) <= 400 for line in openings):
        raise ValueError('Invalid opening line')
    definition = {'title': document['title'], 'payload': document, 'base_score': document['scoring']['base_score'],
                  'max_turns': 12, 'document': document, 'openings': openings}
    cursor.execute('SELECT intent,end_outcome,score_delta,feedback,critical FROM intent_defaults ORDER BY intent')
    definition['intent_defaults'] = cursor.fetchall()
    cursor.execute("SELECT * FROM scenarios WHERE scenario_name=%s FOR UPDATE", (document['id'],))
    scenario = cursor.fetchone()
    if not scenario:
        cursor.execute("""INSERT INTO scenarios(scenario_name,title,difficulty,base_score,status,payload,scenario_kind,family)
                           VALUES(%s,%s,1,%s,'draft',%s,%s,%s) RETURNING *""",
                       (document['id'],document['title'],document['scoring']['base_score'],Jsonb(document),
                        document['scenario_kind'],document['family']))
        scenario=cursor.fetchone()
    definition.update(scenario_kind=document['scenario_kind'],family=document['family'])
    if document['scenario_kind']=='benign':
        definition['intent_defaults']=[{'intent':name,'end_outcome':outcome,'score_delta':delta,'feedback':feedback,'critical':critical}
            for name,outcome,delta,feedback,critical in [('hang_up','timeout',0,'Bạn có quyền kết thúc cuộc gọi.',False),
            ('unknown',None,0,None,False),('share_sensitive','scammed',-50,'Thông tin nhạy cảm không cần cho việc nhận hàng.',True),
            ('transfer_money','scammed',-50,'Đơn đã thanh toán; không cần chuyển thêm tiền.',True)]]
    content_hash = digest(definition)
    sid = scenario['scenario_id']
    cursor.execute('SELECT version_id FROM scenario_versions WHERE scenario_id=%s AND content_hash=%s', (sid, content_hash))
    prior = cursor.fetchone()
    if prior:
        cursor.execute('UPDATE scenarios SET active_version_id=%s WHERE scenario_id=%s', (prior['version_id'], sid))
        return prior['version_id']
    cursor.execute('SELECT COALESCE(max(revision),0)+1 AS revision FROM scenario_versions WHERE scenario_id=%s', (sid,))
    revision = cursor.fetchone()['revision']
    cursor.execute("""INSERT INTO scenario_versions(scenario_id,revision,status,definition,content_hash)
                       VALUES(%s,%s,'draft',%s,%s) RETURNING version_id""", (sid, revision, Jsonb(definition), content_hash))
    vid = cursor.fetchone()['version_id']
    mapping = {}
    terminals = {'END_SAFE': ('safe', 'Cuộc gọi kết thúc. Bạn đã chọn cách xử lý an toàn.'),
                 'END_UNSAFE': ('scammed', 'Cuộc gọi kết thúc sau một hành động rủi ro.'),
                 'END_NEUTRAL': ('timeout', 'Cuộc gọi kết thúc vì chưa đủ thông tin để đánh giá.')}
    if document['scenario_kind']=='benign':
        terminals['END_SAFE']=('safe','Vâng, tôi ghi nhận nội dung mình vừa thống nhất. Cảm ơn anh/chị.')
        terminals['END_NEUTRAL']=('timeout','Vâng, tôi dừng cuộc gọi tại đây. Anh/chị có thể kiểm tra lại trong ứng dụng đã sử dụng.')
    for stage in document['stages']:
        cursor.execute("""INSERT INTO dialogue_nodes(scenario_id,scenario_version_id,node_key,stage,objective,tactic,
                           requested_action,max_turns,is_start) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING node_id""",
                       (sid, vid, stage['id'], stage['id'], stage['objective'], '; '.join(stage['tactics']),
                        stage['requested_action'], stage['max_turns'], stage['id']==document['start_stage_id']))
        mapping[stage['id']] = cursor.fetchone()['node_id']
    for key, (outcome, text) in terminals.items():
        cursor.execute("""INSERT INTO dialogue_nodes(scenario_id,scenario_version_id,node_key,stage,is_terminal,outcome)
                           VALUES(%s,%s,%s,%s,true,%s) RETURNING node_id""", (sid, vid, key, document['stages'][-1]['id'], outcome))
        mapping[key] = cursor.fetchone()['node_id']
        cursor.execute("INSERT INTO dialogue_lines(node_id,line_text,source) VALUES(%s,%s,'fixed')", (mapping[key], text))
    for stage in document['stages']:
        node = mapping[stage['id']]
        for text, reprompt in [(stage['opening_line'], False), (' '.join(stage['fallback_lines']), True)]:
            cursor.execute("INSERT INTO dialogue_lines(node_id,line_text,source,is_reprompt) VALUES(%s,%s,'fixed',%s)", (node, text, reprompt))
        cursor.execute('UPDATE dialogue_nodes SET timeout_next_node_id=%s WHERE node_id=%s', (mapping[stage['timeout_next_stage_id']], node))
        for edge in stage['transitions']:
            candidates = [r for r in document['scoring']['rules'] if r['intent']==edge['on_intent'] and r.get('stage_id') in {None,stage['id']}]
            rule = next((r for r in candidates if r.get('stage_id')==stage['id']), candidates[0] if candidates else {})
            cursor.execute("""INSERT INTO dialogue_transitions(from_node_id,intent,to_node_id,score_delta,feedback,critical)
                               VALUES(%s,%s,%s,%s,%s,%s)""", (node, edge['on_intent'], mapping[edge['next_stage_id']],
                               rule.get('points_delta',0), rule.get('feedback'), rule.get('critical',False)))
    for text in openings:
        cursor.execute("INSERT INTO dialogue_lines(node_id,line_text,source) VALUES(%s,%s,'fixed') ON CONFLICT DO NOTHING", (mapping[document['start_stage_id']], text))
    cursor.execute("UPDATE scenario_versions SET status='published' WHERE version_id=%s", (vid,))
    cursor.execute("UPDATE scenarios SET active_version_id=%s,status='published',scenario_kind=%s,family=%s WHERE scenario_id=%s",
                   (vid,document['scenario_kind'],document['family'],sid))
    return vid
