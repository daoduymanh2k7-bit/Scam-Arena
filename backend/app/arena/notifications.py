"""Persistent SMS/mail/app artifacts for the simulator; never sends external mail."""
from datetime import datetime, timezone, timedelta
import secrets
from fastapi import HTTPException
from app.arena.practice_catalog import FAMILIES,case_spec,render


def install(cursor):
    cursor.execute("""CREATE TABLE IF NOT EXISTS practice_messages (
        message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        session_id UUID NOT NULL REFERENCES call_sessions(session_id) ON DELETE CASCADE,
        message_key TEXT NOT NULL,channel TEXT NOT NULL CHECK(channel IN ('sms','email','app')),
        sender TEXT NOT NULL,subject TEXT NOT NULL,body TEXT NOT NULL,
        code TEXT,created_at TIMESTAMPTZ NOT NULL DEFAULT now(),expires_at TIMESTAMPTZ,
        revoked_at TIMESTAMPTZ,read_at TIMESTAMPTZ,UNIQUE(session_id,message_key)
    );CREATE INDEX IF NOT EXISTS practice_messages_session_idx ON practice_messages(session_id,message_id)""")


def insert(cursor,sid,key,channel,sender,subject,body,code=None):
    cursor.execute("""INSERT INTO practice_messages(session_id,message_key,channel,sender,subject,body,code,expires_at)
                      VALUES(%s,%s,%s,%s,%s,%s,%s,CASE WHEN %s::text IS NULL THEN NULL ELSE now()+interval '3 minutes' END)
                      ON CONFLICT(session_id,message_key) DO NOTHING""",(sid,key,channel,sender,subject,body,code,code))


def seed(cursor,sid,definition,variables):
    family=definition.get('family')
    if family not in FAMILIES: return
    spec=case_spec(definition)
    title={'delivery':'Xác nhận đơn hàng','appointment':'Xác nhận lịch hẹn','support':'Đã nhận yêu cầu hỗ trợ'}[family]
    reference=variables.get('reference','DEMO')
    insert(cursor,sid,'confirmation','email','Trung tâm dịch vụ mô phỏng',f'{title} · {reference}',
           f'Xin chào bạn,\n\nMã hồ sơ: {reference}\n'+render(spec['evidence'],variables)+
           '\n\nBạn có thể tự mở ứng dụng đã dùng trước đó để đối chiếu. Email này thuộc cuộc gọi mô phỏng, không phải thư gửi tới tài khoản thật.')


def otp(cursor,sid,resend=False):
    cursor.execute("SELECT * FROM practice_messages WHERE session_id=%s AND code IS NOT NULL ORDER BY message_id DESC",(sid,))
    previous=cursor.fetchall()
    if previous and not resend: return
    if len(previous)>=3: raise HTTPException(429,'Phiên này đã đạt giới hạn 3 lần cấp mã mô phỏng.')
    if previous and datetime.now(timezone.utc)-previous[0]['created_at']<timedelta(seconds=20):
        raise HTTPException(429,'Chờ ít nhất 20 giây trước khi gửi lại mã.')
    cursor.execute('UPDATE practice_messages SET revoked_at=now() WHERE session_id=%s AND code IS NOT NULL AND revoked_at IS NULL',(sid,))
    code=f'{secrets.randbelow(1000000):06d}'
    insert(cursor,sid,'otp-'+str(len(previous)+1),'sms','Tài khoản mô phỏng','Mã xác nhận đăng nhập',
           f'{code} là mã xác nhận đăng nhập trên thiết bị mới. Hiệu lực 3 phút. Không cung cấp mã cho người gọi.\n\nChỉ dùng trong mô phỏng; không liên quan đến tài khoản thật.',code)


def request_artifact(cursor,sid,action):
    if action=='share_sensitive': otp(cursor,sid)
    elif action in {'click_link','install_app'}:
        insert(cursor,sid,'requested-link','sms','Người liên hệ dịch vụ','Thông tin được gửi trong cuộc gọi',
               'Người gọi đề nghị mở một trang xử lý ngoài ứng dụng đã sử dụng.\n\nĐây là tin nhắn mô phỏng. Nút thao tác mô phỏng không mở website hoặc cài phần mềm thật.')


def brief(cursor,sid):
    cursor.execute('SELECT channel,subject FROM practice_messages WHERE session_id=%s ORDER BY message_id',(sid,))
    return cursor.fetchall()  # No private OTP/body is handed to the caller LLM.
